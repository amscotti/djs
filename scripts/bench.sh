#!/usr/bin/env bash
# Measure the v0.1 runtime and write docs/BENCH.md. Numbers are wall-clock on
# this host; run with the release build and no other load for useful results.
set -euo pipefail
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT"

dub build --build=release --force --compiler=ldc2 >/dev/null
BIN="$ROOT/djs"
RUNS="${DJS_BENCH_RUNS:-100}"

avg_ms() {
    local runs="$1"; shift
    local start end
    start=$(date +%s%N)
    for ((i = 0; i < runs; i++)); do "$@" >/dev/null 2>&1 || true; done
    end=$(date +%s%N)
    awk -v a="$start" -v b="$end" -v n="$runs" 'BEGIN { printf "%.2f", (b-a)/n/1000000 }'
}

startup=$(avg_ms "$RUNS" "$BIN" -A -e '')
hello=$(avg_ms "$((RUNS / 2))" "$BIN" -A -e 'console.log("hi")')
rss=$("$BIN" -A -e 'console.log((process.memoryUsage().rss / 1048576).toFixed(1))')
heap=$("$BIN" -A -e 'console.log((process.memoryUsage().heapUsed / 1048576).toFixed(2))')
loop=$(avg_ms 20 "$BIN" -A -e 'let s = 0; for (let i = 0; i < 1000000; i++) s += i;')
fssync=$(avg_ms 5 "$BIN" -A -e 'for (let i = 0; i < 1000; i++) fs.readFileSync("tests/js/fixtures/hello.txt", "utf8");')
fsasync=$(avg_ms 5 "$BIN" -A -e 'let n = 0; (function next() { fs.promises.readFile("tests/js/fixtures/hello.txt", "utf8").then(() => { if (++n < 1000) next(); }); })();')

node_startup="n/a"
node_loop="n/a"
node_fssync="n/a"
if command -v node >/dev/null 2>&1; then
    node_startup=$(avg_ms "$RUNS" node -e '')
    node_loop=$(avg_ms 20 node -e 'let s = 0; for (let i = 0; i < 1000000; i++) s += i;')
    node_fssync=$(avg_ms 5 node -e 'const fs = require("fs"); for (let i = 0; i < 1000; i++) fs.readFileSync("tests/js/fixtures/hello.txt", "utf8");')
fi

cpu="$(awk -F: '/model name/ { gsub(/^ +/, "", $2); print $2; exit }' /proc/cpuinfo)"
kernel="$(uname -sr)"
ldc="$(ldc2 --version 2>&1 | head -1)"
uv="$(pkg-config --modversion libuv)"
nodever="$(node --version 2>/dev/null || echo none)"
djsver="$(./djs --version)"

if [ "$node_startup" != "n/a" ]; then
    eng_note=$(awk -v d="$loop" -v ds="$startup" -v n="$node_loop" -v ns="$node_startup" \
        'BEGIN { printf "DJS ≈ %.0f ms vs Node ≈ %.0f ms (%.1f× slower)", d - ds, n - ns, (d - ds) / (n - ns) }')
else
    eng_note="Node not installed, so there is no comparison"
fi

cat > docs/BENCH.md <<EOF
# Benchmarks — $djsver

Generated by scripts/bench.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ).

| | |
|---|---|
| CPU | $cpu |
| Kernel | $kernel |
| Compiler | $ldc |
| libuv | $uv |
| Node (comparison) | $nodever |
| Iterations | DJS_BENCH_RUNS=$RUNS (loop/fs: 20/5) |

Wall-clock per invocation, release build with LDC (dub build --build=release --force --compiler=ldc2).

| Measurement | DJS | Node |
|---|---|---|
| Cold start, -e '' (ms) | $startup | $node_startup |
| Hello world, -e 'console.log(...)' (ms) | $hello | — |
| Startup RSS (MiB) | $rss | — |
| QuickJS heap after startup (MiB) | $heap | — |
| 1M-iteration integer loop (ms) | $loop | $node_loop |
| 1,000 sync fs reads (ms) | $fssync | $node_fssync |
| 1,000 chained async fs reads (ms) | $fsasync | — |

## Reading these numbers

- **Cold start** includes process creation, QuickJS runtime/context creation,
  prelude evaluation and teardown. Process creation dominates it; the engine's
  own share is small.
- **RSS** is the whole process; heapUsed is what --memory-limit governs.
  The difference is libuv, the binary, D runtime and allocator slack.
- **CPU loop** includes process startup. Subtract cold start for an engine-only
  estimate: $eng_note on this loop. This is the documented trade
  (ARCH ADR-001): DJS is for glue, tooling and I/O-bound automation, not
  compute.
- **fs** numbers include process start; subtract cold start for the I/O cost.
  Sync reads are one blocking open/read/close per file on the loop thread;
  async reads use the libuv threadpool and a promise microtask per read.
- Numbers vary with filesystem cache state and host load. Re-run before
  quoting them.
EOF

printf 'bench: startup=%sms hello=%sms rss=%sMiB loop=%sms fs_sync=%sms fs_async=%sms\n' \
    "$startup" "$hello" "$rss" "$loop" "$fssync" "$fsasync"
